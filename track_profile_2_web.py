def _fetch_mapterhorn_tile(zoom, x, y):
    url = 'https://tiles.mapterhorn.com/{}/{}/{}.webp'.format(zoom, x, y)
    request = Request(url, headers={'User-Agent': 'TrackProfile2Web'})
    try:
        with urlopen(request, timeout=15) as response:
            image = QImage.fromData(response.read())
    except HTTPError as error:
        if error.code == 404:
            return None
        raise
    if image.isNull() or image.width() != 512 or image.height() != 512:
        raise RuntimeError("Mapterhorn returned an invalid elevation tile.")
    return image


def _sample_mapterhorn_elevation(lon, lat, get_tile):
    lat = max(-85.05112878, min(85.05112878, lat))
    lon = (lon + 180) % 360 - 180
    lat_radians = math.radians(lat)
    best_elevation = None

    def tile_position(zoom):
        tile_count = 2 ** zoom
        x = (lon + 180) / 360 * tile_count
        y = (1 - math.asinh(math.tan(lat_radians)) / math.pi) / 2 * tile_count
        return x, y, int(x), int(y)

    for zoom in range(13, 20):
        x, y, tile_x, tile_y = tile_position(zoom)
        image = get_tile(zoom, tile_x, tile_y)
        if image is None:
            break
        color = image.pixelColor(
            min(511, int((x - tile_x) * 512)),
            min(511, int((y - tile_y) * 512))
        )
        if color.alpha():
            best_elevation = color.red() * 256 + color.green() + color.blue() / 256 - 32768

    if best_elevation is None:
        x, y, tile_x, tile_y = tile_position(12)
        image = get_tile(12, tile_x, tile_y)
        if image is not None:
            color = image.pixelColor(
                min(511, int((x - tile_x) * 512)),
                min(511, int((y - tile_y) * 512))
            )
            if color.alpha():
                best_elevation = color.red() * 256 + color.green() + color.blue() / 256 - 32768

    if best_elevation is None:
        raise ValueError("Mapterhorn has no elevation data at {:.6f}, {:.6f}.".format(lon, lat))
    return best_elevation


def _layer_with_mapterhorn_elevations(layer):
    destination_crs = QgsCoordinateReferenceSystem('EPSG:4326')
    transform = QgsCoordinateTransform(layer.crs(), destination_crs, QgsProject.instance())
    geometry_type = QgsWkbTypes.displayString(
        QgsWkbTypes.addZ(QgsWkbTypes.dropM(layer.wkbType()))
    )
    output = QgsVectorLayer(
        '{}?crs=EPSG:4326'.format(geometry_type),
        layer.name(),
        'memory'
    )
    if not output.isValid():
        raise RuntimeError("Could not create the temporary 3D line layer.")

    provider = output.dataProvider()
    provider.addAttributes(layer.fields())
    output.updateFields()
    tile_cache = {}

    def get_tile(zoom, x, y):
        key = (zoom, x, y)
        if key not in tile_cache:
            tile_cache[key] = _fetch_mapterhorn_tile(zoom, x, y)
        return tile_cache[key]

    features = []
    for source_feature in layer.getFeatures():
        geometry = source_feature.geometry()
        if layer.crs().authid() != 'EPSG:4326':
            geometry.transform(transform)
        geometry_json = json.loads(geometry.asJson())

        def add_elevations(coordinates):
            if not coordinates:
                return coordinates
            if isinstance(coordinates[0], (int, float)):
                return [
                    coordinates[0],
                    coordinates[1],
                    _sample_mapterhorn_elevation(
                        coordinates[0], coordinates[1], get_tile
                    )
                ]
            return [add_elevations(part) for part in coordinates]

        geometry_json['coordinates'] = add_elevations(geometry_json['coordinates'])
        elevated_feature = QgsFeature(output.fields())
        elevated_feature.setAttributes(source_feature.attributes())
        elevated_geometry = QgsJsonUtils.geometryFromGeoJson(json.dumps(geometry_json))
        if elevated_geometry.isNull():
            raise RuntimeError("Could not create the elevated geometry.")
        elevated_feature.setGeometry(elevated_geometry)
        features.append(elevated_feature)

    added = provider.addFeatures(features)
    if not (added[0] if isinstance(added, tuple) else added):
        raise RuntimeError("Could not populate the temporary 3D line layer.")
    output.updateExtents()
    return output


class PreviewBridge(QObject):
    stateChanged = pyqtSignal()
    previewChanged = pyqtSignal(str)

    def __init__(self, dialog):
        super().__init__(dialog)
        self.dialog = dialog

    @pyqtSlot(result=str)
    def state(self):
        dialog = self.dialog
        layers = [dialog.layer_combo.layer(i) for i in range(dialog.layer_combo.count())]
        selected = dialog.layer_combo.currentLayer()
        message = dialog.bar.currentItem()
        return json.dumps({
            "layers": [{"id": layer.id(), "name": layer.name()} for layer in layers if layer],
            "layer": selected.id() if selected else "",
            "preview": dialog._preview_url,
            "settings": dialog.settings,
            "ready": dialog._preview_status == "ready",
            "status": dialog._preview_status,
            "message": {
                "title": message.title(),
                "text": message.text(),
                "error": message.level() == Qgis.MessageLevel.Critical,
            } if message else None,
        })

    @pyqtSlot(str)
    def selectLayer(self, layer_id):
        for i in range(self.dialog.layer_combo.count()):
            layer = self.dialog.layer_combo.layer(i)
            if layer and layer.id() == layer_id:
                self.dialog.layer_combo.setLayer(layer)
                return
        self.dialog.bar.pushMessage(
            self.dialog.tr("The selected layer is no longer available."),
            level=Qgis.MessageLevel.Warning, duration=5
        )

    @pyqtSlot()
    def retry(self):
        self.dialog._source_changed()

    @pyqtSlot(str)
    def setOptions(self, value):
        try:
            settings = json.loads(value)
            valid = (
                isinstance(settings, dict)
                and isinstance(settings.get("basemap"), str) and bool(settings["basemap"])
                and isinstance(settings.get("basemapUrl"), str) and bool(settings["basemapUrl"])
                and isinstance(settings.get("basemapAttribution"), str)
                and settings.get("position") in ("topright", "topleft", "bottomright", "bottomleft")
                and all(isinstance(settings.get(key), str) and
                        re.fullmatch(r"#[0-9a-fA-F]{6}", settings[key])
                        for key in ("profileColor", "lineColor", "markerColor"))
                and all(type(settings.get(key)) is bool for key in
                        ("detached", "follow", "collapseProfile", "collapseLayers", "autohide",
                         "slope", "imperial", "distanceMarkers", "hotline", "legend", "ruler",
                         "trackEndpoints", "edgeScale", "autofitBounds", "rotateMap",
                         "terrain3D", "autohideMarker"))
                and settings.get("marker") in ("elevation-line", "position-marker")
                and all(settings.get(key) in ("auto", "enabled", "disabled")
                        for key in ("dragging", "zooming"))
                and settings.get("interpolation") in
                    ("curveLinear", "curveStep", "curveStepBefore", "curveStepAfter")
                and all(type(settings.get(key)) in (int, float) and
                        math.isfinite(settings[key]) and 0 <= settings[key] <= maximum
                        for key, maximum in (("profileWidth", 10), ("markerOpacity", 1)))
                and all(settings.get(key) is None or
                        (type(settings[key]) is int and 120 <= settings[key] <= maximum)
                        for key, maximum in (("width", 4096), ("height", 1200)))
                and all(settings.get(key) is None or
                        (type(settings[key]) is int and minimum <= settings[key] <= maximum)
                        for key, minimum, maximum in
                        (("xTicks", 1, 100), ("yTicks", 1, 100), ("decimalsX", 0, 10),
                         ("decimalsY", 0, 10), ("zFollow", 0, 22)))
                and all(settings.get(key) is None or
                        (type(settings[key]) in (int, float) and math.isfinite(settings[key])
                         and (not key.startswith("x") or settings[key] >= 0))
                        for key in ("xAxisMin", "xAxisMax", "yAxisMin", "yAxisMax"))
                and all(settings.get(axis + "AxisMin") is None or
                        settings.get(axis + "AxisMax") is None or
                        settings[axis + "AxisMin"] < settings[axis + "AxisMax"]
                        for axis in ("x", "y"))
            )
        except (ValueError, TypeError, OverflowError):
            valid = False
        if not valid:
            self.dialog.bar.pushMessage(
                self.dialog.tr("Invalid setting."),
                level=Qgis.MessageLevel.Warning, duration=5
            )
            return
        if settings != self.dialog.settings:
            was_3d = bool(self.dialog.settings and self.dialog.settings["terrain3D"])
            if settings["terrain3D"] and not was_3d and not self.dialog.open_3d_preview():
                return
            self.dialog.settings = settings
            self.dialog._schedule_preview()
            if settings["terrain3D"] and not was_3d:
                self.dialog.hide()
            elif was_3d and not settings["terrain3D"]:
                self.dialog.showMaximized()
                self.dialog.mapview.reload()

    @pyqtSlot(str)
    def action(self, action):
        actions = {
            "html": self.dialog.saveAsHtml,
            "geojson": self.dialog.saveAsHtmlGeojson,
        }
        if action in actions and self.dialog._preview_status == "ready":
            actions[action]()
        else:
            self.dialog.bar.pushMessage(
                self.dialog.tr("The requested action is not available."),
                level=Qgis.MessageLevel.Warning, duration=5
            )


class PreviewServer(QObject):
    def __init__(self, dialog, panel):
        super().__init__(dialog)
        self.dialog = dialog
        self.panel = panel.encode('utf-8')
        self.token = secrets.token_urlsafe(32)
        self.server = QTcpServer(self)
        self.server.newConnection.connect(self.accept)
        if not self.server.listen(QHostAddress(QHostAddress.SpecialAddress.LocalHost), 0):
            raise RuntimeError("Could not start the local preview server: " + self.server.errorString())
        self.origin = 'http://127.0.0.1:{}'.format(self.server.serverPort())
        self.base_url = '{}/{}/'.format(self.origin, self.token)
        self.buffers = {}

    def accept(self):
        while self.server.hasPendingConnections():
            socket = self.server.nextPendingConnection()
            if len(self.buffers) >= 32:
                socket.abort()
                socket.deleteLater()
                continue
            self.buffers[socket] = bytearray()
            socket.request_timer = QTimer(socket)
            socket.request_timer.setSingleShot(True)
            socket.request_timer.timeout.connect(socket.abort)
            socket.request_timer.start(10000)
            socket.readyRead.connect(lambda s=socket: self.read(s))
            socket.disconnected.connect(lambda s=socket: self.discard(s))

    def discard(self, socket):
        self.buffers.pop(socket, None)
        socket.deleteLater()

    def respond(self, socket, status, content_type, body):
        headers = (
            'HTTP/1.1 {}\r\nContent-Type: {}\r\nContent-Length: {}\r\n'
            'Cache-Control: no-store\r\nReferrer-Policy: no-referrer\r\n'
            'X-Content-Type-Options: nosniff\r\nConnection: close\r\n\r\n'
        ).format(status, content_type, len(body)).encode('ascii')
        socket.write(headers + body)
        socket.disconnectFromHost()

    def read(self, socket):
        data = self.buffers.get(socket)
        if data is None:
            return
        data.extend(bytes(socket.readAll()))
        if len(data) > 131072:
            self.respond(socket, '413 Payload Too Large', 'text/plain', b'Request too large')
            return
        header_end = data.find(b'\r\n\r\n')
        if header_end < 0:
            return
        try:
            lines = bytes(data[:header_end]).decode('iso-8859-1').split('\r\n')
            method, path, version = lines[0].split(' ')
            headers = {}
            for line in lines[1:]:
                name, value = line.split(':', 1)
                name = name.lower()
                if name in headers:
                    raise ValueError('Duplicate header')
                headers[name] = value.strip()
            length = int(headers.get('content-length', '0'))
            if length < 0 or length > 65536 or version not in ('HTTP/1.0', 'HTTP/1.1'):
                raise ValueError('Invalid request')
        except ValueError:
            self.respond(socket, '400 Bad Request', 'text/plain', b'Invalid request')
            return
        if len(data) < header_end + 4 + length:
            return
        socket.request_timer.stop()
        self.buffers[socket] = None
        if headers.get('host') != self.origin.removeprefix('http://'):
            self.respond(socket, '403 Forbidden', 'text/plain', b'Forbidden')
            return
        path = path.split('?', 1)[0]
        prefix = '/' + self.token + '/'
        if not path.startswith(prefix):
            self.respond(socket, '404 Not Found', 'text/plain', b'Not found')
            return
        route = path[len(prefix):]
        if method == 'GET' and route == '':
            self.respond(socket, '200 OK', 'text/html; charset=utf-8', self.panel)
        elif method == 'GET' and route == 'state':
            self.respond(socket, '200 OK', 'application/json', self.dialog.bridge.state().encode('utf-8'))
        elif method == 'GET' and route == 'map.html' and self.dialog._preview_url:
            try:
                with open(self.dialog.fout, 'rb') as preview:
                    body = preview.read()
            except OSError as error:
                self.respond(socket, '500 Internal Server Error', 'text/plain',
                             ('Could not read the preview: ' + str(error)).encode('utf-8'))
                return
            self.respond(socket, '200 OK', 'text/html; charset=utf-8', body)
        elif method == 'POST' and route == 'command' and headers.get('origin') == self.origin:
            try:
                command = json.loads(bytes(data[header_end + 4:header_end + 4 + length]))
                name, value = command['name'], command.get('value', '')
                if name not in ('setOptions', 'selectLayer', 'retry', 'action') or not isinstance(value, str):
                    raise ValueError('Invalid command')
            except (ValueError, KeyError, TypeError):
                self.respond(socket, '400 Bad Request', 'text/plain', b'Invalid command')
                return
            if name == 'retry':
                self.dialog.bridge.retry()
            else:
                getattr(self.dialog.bridge, name)(value)
            self.respond(socket, '200 OK', 'application/json', b'{}')
        else:
            self.respond(socket, '404 Not Found', 'text/plain', b'Not found')


class TrackProfile2webDialog(QtWidgets.QDialog):
    def __init__(self, parent=None):
        """Constructor."""
        super(TrackProfile2webDialog, self).__init__(parent)
        self.setWindowTitle(self.tr("Leaflet Elevation"))
        self.resize(948, 591)
        self.mapview = QWebEngineView(self)
        layout = QtWidgets.QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.addWidget(self.mapview)
        self.preview_dir = tempfile.TemporaryDirectory(prefix='trackprofile2web-')
        self._closed = False
        # filter only QgsVector Line Layers
        self.layer_combo = QgsMapLayerComboBox(self)
        self.layer_combo.hide()
        self.layer_combo.setFilters(Qgis.LayerFilter.LineLayer)

        # create instance of QgsMessageBar (used later)
        self.bar = QgsMessageBar(self)
        self.bar.hide()

        self.settings = None
        self._source_layer = None
        self._elevated_layer = None
        self._preview_url = ""
        self._preview_status = "empty"
        self.bridge = PreviewBridge(self)
        self.bar.widgetAdded.connect(self.bridge.stateChanged)
        self.bar.widgetRemoved.connect(self.bridge.stateChanged)
        self._preview_timer = QTimer(self)
        self._preview_timer.setSingleShot(True)
        self._preview_timer.setInterval(250)
        self._preview_timer.timeout.connect(self.changeMap)
        self.layer_combo.layerChanged.connect(self._set_source_layer)
        QgsProject.instance().layersAdded.connect(self.bridge.stateChanged)
        QgsProject.instance().layersRemoved.connect(self.bridge.stateChanged)
        self._set_source_layer(self.layer_combo.currentLayer())
        template_path = os.path.join(os.path.dirname(__file__), 'track_profile_2_web.html')
        with open(template_path, encoding='utf-8') as template_file:
            before, preview = template_file.read().split('<template id="qgis-preview">', 1)
            preview, after = preview.split('</template>', 1)
        self.map_template = before + after
        self.server = PreviewServer(self, '<!DOCTYPE html>\n' + preview)
        self._preview_revision = 0
        self.mapview.setUrl(QUrl(self.server.base_url + '?embedded=1'))

    def open_3d_preview(self):
        answer = QtWidgets.QMessageBox.question(
            self, self.tr("Open 3D preview in browser"),
            self.tr(
                "3D terrain requires WebGPU, which may not be available in QGIS.\n\n"
                "Open the preview in your default browser? Keep QGIS open to change "
                "settings and export the map."
            ),
            QtWidgets.QMessageBox.StandardButton.Yes | QtWidgets.QMessageBox.StandardButton.No,
            QtWidgets.QMessageBox.StandardButton.No
        )
        if answer != QtWidgets.QMessageBox.StandardButton.Yes:
            return False
        if not QDesktopServices.openUrl(QUrl(self.server.base_url)):
            self.bar.pushMessage(
                self.tr("Could not open the default browser."),
                level=Qgis.MessageLevel.Critical, duration=15
            )
            return False
        return True

    def shutdown(self):
        if self._closed:
            return
        self._closed = True
        self._preview_timer.stop()
        self._set_source_layer(None)
        QgsProject.instance().layersAdded.disconnect(self.bridge.stateChanged)
        QgsProject.instance().layersRemoved.disconnect(self.bridge.stateChanged)
        self.server.server.close()
        for socket in list(self.server.buffers):
            socket.abort()
        self.preview_dir.cleanup()

    def _set_source_layer(self, layer):
        signals = ('dataChanged', 'geometryChanged', 'featureAdded', 'featureDeleted',
                   'attributeValueChanged', 'crsChanged', 'nameChanged')
        if self._source_layer is not None:
            for name in signals:
                try:
                    getattr(self._source_layer, name).disconnect(self._source_changed)
                except (RuntimeError, TypeError):
                    pass
        self._source_layer = layer
        if layer is not None:
            for name in signals:
                getattr(layer, name).connect(self._source_changed)
        self._source_changed()

    def _source_changed(self, *args):
        self._elevated_layer = None
        self._preview_url = ""
        self.bridge.previewChanged.emit("")
        self._schedule_preview()

    def _schedule_preview(self, *args):
        if self._closed:
            return
        self._preview_status = "updating" if self.layer_combo.currentLayer() else "empty"
        self.bridge.stateChanged.emit()
        if self.settings is not None:
            self._preview_timer.start()

    def changeMap(self):
        '''
        Main function of the plugin. Draws the map with the Line layer and
        tweaks all the options chosen
        '''

        # reference of the main QgsVectorLayer
        vlayer = self.layer_combo.currentLayer()

        if self.settings is None:
            return
        if vlayer is None:
            self._preview_url = ""
            self.bridge.previewChanged.emit("")
            return

        self._used_mapterhorn = False
        if not QgsWkbTypes.hasZ(vlayer.wkbType()):
            if self._elevated_layer is None:
                self.bar.pushMessage(
                    self.tr("Getting elevations from Mapterhorn..."),
                    level=Qgis.MessageLevel.Info,
                    duration=5
                )
                try:
                    self._elevated_layer = _layer_with_mapterhorn_elevations(vlayer)
                except (OSError, RuntimeError, ValueError, QgsCsException) as error:
                    self._preview_status = "error"
                    self.bar.pushMessage(
                        self.tr("Could not get elevations from Mapterhorn."),
                        str(error),
                        level=Qgis.MessageLevel.Critical,
                        duration=15
                    )
                    self.bridge.stateChanged.emit()
                    return
            vlayer = self._elevated_layer
            self._used_mapterhorn = True

        self.vlayer = vlayer

        data = {"name": self.vlayer.name(), "type": "FeatureCollection", "features": []}

        # set the QgsCoordinateTransform context used in to reproject the layer if needed
        crsSrc = self.vlayer.crs()
        crsDest = QgsCoordinateReferenceSystem('EPSG:4326')
        xform = QgsCoordinateTransform(crsSrc, crsDest, QgsProject.instance())

        # start the loop to write the data formatted in the correct way
        for i in self.vlayer.getFeatures():

            geometry = i.geometry()

            # transform the geometry to 4326 if needed
            if not self.vlayer.crs().authid() == 'EPSG:4326':
                geometry.transform(xform)
            data["features"].append({
                "type": "Feature", "properties": {}, "geometry": json.loads(geometry.asJson())
            })

        self.config = {"data": json.dumps(data), "settings": dict(self.settings)}
        if self._used_mapterhorn:
            self.config["settings"]["basemapAttribution"] += (
                ' | Elevation: <a href="https://mapterhorn.com/attribution">'
                '© Mapterhorn</a>'
            )

        # get the path (from tempfolder) where to write the final result
        self.fout = os.path.join(self.preview_dir.name, 'template.html')

        if "'{ py_opts }'" not in self.map_template:
            raise ValueError("Missing template placeholder: { py_opts }")

        # write the final file
        with open(self.fout, 'w', encoding='utf-8') as fo:
            fo.write(self.map_template.replace(
                "'{ py_opts }'", json.dumps(self.config).replace('</', '<\\/')
            ))

        # get the path of the output file as QUrl
        self._preview_revision += 1
        self._preview_url = self.server.base_url + 'map.html?revision=' + str(self._preview_revision)
        self.bridge.previewChanged.emit(self._preview_url)
        self._preview_status = "ready"
        self.bridge.stateChanged.emit()


    def saveAsHtml(self):
        '''
        Open a dialog and let the user choose the location to write the file.
        The file is a single html with the injected data as geojson.
        '''

        dial, _ = QFileDialog.getSaveFileName(None, self.tr("Save Elevation file"), "", "*.html")
        if not dial:
            return
        elevation_file = QFileInfo(dial).absoluteFilePath()
        if not elevation_file.lower().endswith('.html'):
            elevation_file += '.html'

        try:
            copyfile(self.fout, elevation_file)
            self.bar.pushMessage(self.tr("Elevation file succesfully saved"), "", level=Qgis.MessageLevel.Info, duration=3)
        except OSError as error:
            self.bar.pushMessage(self.tr("Something went wrong. Try again."), str(error), level=Qgis.MessageLevel.Critical, duration=3)


    def saveAsHtmlGeojson(self):
        '''
        Open a directory dialog and le the user choose the location where to
        write the html and the geojson file.
        '''

        export_name = re.sub(r'\s+','-', self.vlayer.name())

        dir_path = QFileDialog.getExistingDirectory(None, self.tr("Select Directory"))
        if not dir_path:
            return
        html_name = os.path.join(dir_path, '{}.html'.format(export_name))
        # remove all spaces from name
        gjson_name = os.path.join(dir_path, '{}.geojson'.format(export_name))

        options = QgsVectorFileWriter.SaveVectorOptions()
        options.driverName = 'GeoJSON'
        options.fileEncoding = 'UTF-8'
        options.ct = QgsCoordinateTransform(self.vlayer.crs(), QgsCoordinateReferenceSystem('EPSG:4326'), QgsProject.instance())
        output = QgsVectorFileWriter.writeAsVectorFormatV3(
            self.vlayer, gjson_name, QgsProject.instance().transformContext(), options)
        if output[0] != QgsVectorFileWriter.WriterError.NoError:
            self.bar.pushMessage(self.tr("Something went wrong. Try again."), output[1], level=Qgis.MessageLevel.Critical, duration=3)
            return

        # change the raw geojson string with the relative file path
        geojson_config = dict(self.config, data=quote(os.path.basename(gjson_name)))

        # write the final file
        try:
            with open(html_name, 'w', encoding='utf-8') as fog:
                fog.write(self.map_template.replace(
                    "'{ py_opts }'", json.dumps(geojson_config).replace('</', '<\\/')
                ))
            self.bar.pushMessage(self.tr("Elevation file succesfully saved"), "", level=Qgis.MessageLevel.Info, duration=3)
        except OSError as error:
            self.bar.pushMessage(self.tr("Something went wrong. Try again."), str(error), level=Qgis.MessageLevel.Critical, duration=3)


class TrackProfile2web:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        self.iface = iface
        self.plugin_dir = os.path.dirname(__file__)
        locale = (QSettings().value('locale/userLocale') or 'en')[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            'TrackProfile2web_{}.qm'.format(locale))

        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)

            if qVersion() > '4.3.3':
                QCoreApplication.installTranslator(self.translator)

        self.actions = []
        self.menu = self.tr(u'&Track Profile to Web')
        self.first_start = None

    def tr(self, message):
        """Get the translation for a string using Qt translation API."""
        return QCoreApplication.translate('TrackProfile2web', message)

    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""
        icon_path = os.path.join(self.plugin_dir, 'icon.png')
        action = QAction(QIcon(icon_path), self.tr(u'Tracks Profile To Web'),
                         self.iface.mainWindow())
        action.triggered.connect(self.run)
        self.iface.addToolBarIcon(action)
        self.iface.addPluginToWebMenu(self.menu, action)
        self.actions.append(action)
        self.first_start = True

    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        for action in self.actions:
            self.iface.removePluginWebMenu(
                self.tr(u'&Track Profile to Web'),
                action)
            self.iface.removeToolBarIcon(action)
        if hasattr(self, 'dlg'):
            self.dlg.shutdown()
            self.dlg.deleteLater()

    def run(self):
        """Run method that performs all the real work."""
        if self.first_start == True:
            try:
                self.dlg = TrackProfile2webDialog()
            except (OSError, RuntimeError) as error:
                self.iface.messageBar().pushCritical(
                    self.tr("Track Profile to Web"), str(error)
                )
                return
            self.first_start = False
        if self.dlg.settings and self.dlg.settings["terrain3D"]:
            self.dlg.open_3d_preview()
        else:
            self.dlg.showMaximized()
